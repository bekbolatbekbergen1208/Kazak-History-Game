export function taskAnswer(task: Task): string {
  return task.type === "choice"
    ? task.correct!.map((i) => task.options![i]).join("; ")
    : task.type === "sort"
      ? task.items!.map((i) => `${i.text} → ${i.group}`).join("\n")
      : task.type === "order"
        ? task.sequence!.join(" → ")
        : task.type === "map"
          ? "Жетісу және Торғай: екі архивті де зерттеу."
          : "2–3 дәлел және кемінде 15 таңбалық жеке қорытынды. Пікір автоматты бағаланбайды.";
}

